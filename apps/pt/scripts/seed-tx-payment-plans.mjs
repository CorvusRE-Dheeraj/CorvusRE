// Turns src/data/tx-payment-plans.json (build-tx-payment-plans.mjs) into SQL
// for county_tax_settings / county_payment_plans:
//
//   node scripts/seed-tx-payment-plans.mjs > ../../supabase/pt/pay-taxes-counties.sql
//
// Every county gets its research row. A county whose own site states the
// half-payment option gets a Half-Payment Plan (sourced to that page). Staff
// edits win: a finding never downgrades a county someone set by hand to
// "unknown", and an existing plan row is left as it is.

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const data = JSON.parse(
  fs.readFileSync(path.join(here, "../src/data/tx-payment-plans.json"), "utf8"),
);

const q = (v) => (v == null || v === "" ? "null" : `'${String(v).replace(/'/g, "''")}'`);
const HALF_SCHEDULE = JSON.stringify([
  { label: "First half", pct: 50, month: 11, day: 30, yearOffset: 0 },
  { label: "Second half", pct: 50, month: 6, day: 30, yearOffset: 1 },
]);

const settings = [];
const plans = [];
for (const c of Object.values(data.counties)) {
  const half = c.evidence?.half ?? c.evidence?.noHalf ?? null;
  const other = Object.fromEntries(
    Object.entries(c.evidence ?? {}).filter(([k]) => !["half", "noHalf"].includes(k)),
  );
  settings.push(
    `(${q(c.county)}, ${q(c.halfPayment)}, ${q(half?.quote?.slice(0, 600))}, ${q(half?.url)}, ${q(JSON.stringify(other))}::jsonb, ${q(data.builtAt)}::date)`,
  );
  if (c.halfPayment === "offered")
    plans.push(
      `(${q(c.county)}, 'half_payment', 'Half-Payment Plan', 'half', '{}', null, ${q(HALF_SCHEDULE)}::jsonb, ` +
        `'Pay half by November 30 and the rest by June 30 without penalty or interest (Tax Code §31.03). A late first half generally cancels the split — confirm the details with the county tax office.', ` +
        `'confirmed', ${q(half.url)})`,
    );
}

console.log(`-- Generated by apps/pt/scripts/seed-tx-payment-plans.mjs from tx-payment-plans.json (${data.builtAt}).
-- ${settings.length} counties; ${plans.length} with a sourced half-payment plan (county site, or a verified report — see the quote).
insert into public.county_tax_settings (county, half_payment, half_payment_quote, half_payment_url, other_options, rules_checked_at) values
${settings.join(",\n")}
on conflict (county) do update set
  half_payment = case when excluded.half_payment <> 'unknown' or county_tax_settings.half_payment = 'unknown'
    then excluded.half_payment else county_tax_settings.half_payment end,
  half_payment_quote = case when excluded.half_payment <> 'unknown' or county_tax_settings.half_payment = 'unknown'
    then excluded.half_payment_quote else county_tax_settings.half_payment_quote end,
  half_payment_url = case when excluded.half_payment <> 'unknown' or county_tax_settings.half_payment = 'unknown'
    then excluded.half_payment_url else county_tax_settings.half_payment_url end,
  other_options = excluded.other_options,
  rules_checked_at = excluded.rules_checked_at;
${
  plans.length
    ? `
insert into public.county_payment_plans (county, plan_key, name, kind, property_types, requirement, schedule, enrollment_note, status, source_url) values
${plans.join(",\n")}
on conflict (county, plan_key) do nothing;`
    : ""
}`);
